// Validate and archive local candidate only. No network, push or PR operations.
import fs from 'node:fs';
import path from 'node:path';
import crypto from 'node:crypto';
import {spawnSync} from 'node:child_process';
import {JK,toolRequire} from '../tools/common.mjs';
const prep='/home/fulutang/Documents/Github/VRCX-0-Themes-JiraiKeiKuteWin98-release-prep';
const root=path.join(JK,'release');
const themeDir=path.join(prep,'themes/jirai-kei-theme');
const files=['theme.css','theme.json','README.md','preview.webp'];
const expected=['README.md','themes/index.json',...files.map(f=>'themes/jirai-kei-theme/'+f)].sort();
const hash=b=>crypto.createHash('sha256').update(b).digest('hex');
const run=(cmd,args,opts={})=>{const r=spawnSync(cmd,args,{encoding:'utf8',maxBuffer:32<<20,...opts});if(r.status!==0)throw Error(r.stderr||r.stdout);return r.stdout};
console.log(run(process.execPath,['scripts/validate-themes.mjs'],{cwd:prep}));
console.log(run(process.execPath,['--test','scripts/validate-themes.test.mjs'],{cwd:prep}));
run('git',['add','--intent-to-add','--','themes/jirai-kei-theme'],{cwd:prep});
run('git',['diff','--check'],{cwd:prep});
const changed=run('git',['diff','--name-only','HEAD'],{cwd:prep}).trim().split('\n').sort();
if(JSON.stringify(changed)!==JSON.stringify(expected))throw Error('Unexpected PR paths: '+JSON.stringify(changed));
const css=fs.readFileSync(path.join(themeDir,'theme.css'),'utf8');
const before=fs.readFileSync(path.join(JK,'runtime/preview-package/jirai-kei-theme/theme.css'),'utf8');
function urls(s){return [...s.matchAll(/url\(\s*(?:"([^"\n]*)"|'([^'\n]*)'|([^\s)]*))\s*\)/g)].map(m=>m[1]??m[2]??m[3]);}
const oldUrls=urls(before),newUrls=urls(css);
if(JSON.stringify(oldUrls)!==JSON.stringify(newUrls))throw Error('Embedded resource URL changed during formatting');
if(newUrls.some(u=>!u.startsWith('data:')&&!u.startsWith('#')))throw Error('External or relative resource URL found');
for(const [f,label] of [['original-assets/icons/LUCIDE-LICENSE.txt','Lucide/Feather'],['fonts/OFL-Fusion-Pixel.txt','Fusion Pixel'],['fonts/OFL-Silkscreen.txt','Silkscreen']]){
 const license=fs.readFileSync(path.join(JK,f),'utf8').trim();
 const normalize=s=>s.replace(/\s+/g,' ');
 if(!normalize(css).includes(normalize(license)))throw Error('License notice missing: '+label);
}
const sharp=toolRequire('sharp');const metadata=await sharp(path.join(themeDir,'preview.webp')).metadata();
if(metadata.format!=='webp')throw Error('Invalid preview format');
const report=JSON.parse(fs.readFileSync(path.join(root,'package-report.json'),'utf8'));
report.files=Object.fromEntries(files.map(f=>{const b=fs.readFileSync(path.join(themeDir,f));return [f,{bytes:b.length,sha256:hash(b)}]}));
report.cssBytes=report.files['theme.css'].bytes;
report.sha256=report.files['theme.css'].sha256;
report.preview={width:metadata.width,height:metadata.height,synthetic:true,personalData:false};
report.embeddedResourceCount=newUrls.length;report.embeddedResourcesUnchanged=true;
report.prPaths=changed;report.pushed=false;report.prCreated=false;
const style=JSON.parse(fs.readFileSync(path.join(root,'format-style-diff.json'),'utf8'));
if(style.pages.length!==42||style.pages.some(p=>p.differences!==0||p.restoreProblems.length))throw Error('Frozen page style regression failed');
report.formatStyleReport='format-style-diff.json';
report.formattingNote='Raw/normalized AST strings differ due to quote, whitespace and number formatting. Embedded URL payloads and their order are byte-identical; frozen-page computed-style equivalence is checked separately.';
report.validation={repositoryValidator:true,validatorUnitTests:'3 passed',frozenPages:'42 passed, zero computed-style differences',diffCheck:true};
if(report.files['theme.css'].bytes>1048576||report.files['preview.webp'].bytes>262144)throw Error('Size limit exceeded');
const patch=run('git',['diff','--binary','HEAD'],{cwd:prep});
fs.writeFileSync(path.join(root,'jirai-kei-theme-upstream-candidate.patch'),patch);
const zip=path.join(root,'jirai-kei-theme-1.0.0-rc.1-local-only.zip');
run('python3',['-c',`import zipfile,pathlib,sys\nsrc=pathlib.Path(sys.argv[1])\nwith zipfile.ZipFile(sys.argv[2],'w',zipfile.ZIP_DEFLATED,compresslevel=9) as z:\n for name in ['theme.css','theme.json','README.md','preview.webp']:\n  z.write(src/name,'jirai-kei-theme/'+name)\nwith zipfile.ZipFile(sys.argv[2]) as z:\n assert z.testzip() is None\n assert len(z.infolist())==4\n print('Archive verified:',z.namelist())`,themeDir,zip]);
report.archive={file:path.basename(zip),bytes:fs.statSync(zip).size,sha256:hash(fs.readFileSync(zip)),verified:true};
fs.writeFileSync(path.join(root,'package-report.json'),JSON.stringify(report,null,2)+'\n');
console.log(JSON.stringify({files:report.files,archive:report.archive,prPaths:changed,embeddedResources:newUrls.length,publicDistributionReady:false},null,2));
