// 每行的连续 'X' 段 -> M{x} {y}h{w}v1h-{w}
function toPath(rows) {
  const segs = [];
  rows.forEach((row, y) => {
    let x = 0;
    while (x < row.length) {
      if (row[x] === 'X') {
        let w = 1;
        while (x + w < row.length && row[x + w] === 'X') w++;
        segs.push(`M${x} ${y}h${w}v1h-${w}`);
        x += w;
      } else {
        x++;
      }
    }
  });
  return segs.join(' ');
}

